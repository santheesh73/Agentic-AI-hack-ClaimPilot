// Rewrites the README's <!-- EVAL:START --> ... <!-- EVAL:END --> block from
// the JSON files `pnpm eval` writes to evals/results/. Every number in the
// block comes from those files; nothing is typed in by hand.
//
//   pnpm eval:readme                 # use every evals/results/*.json
//   pnpm eval:readme -- a.json b.json  # use only these runs
//
// With no result files it exits non-zero and leaves README.md untouched.

import fs from "node:fs";
import path from "node:path";

export type EvalResult = {
  case: string;
  expected: string;
  got: string;
  verifiedPct: number;
  steps: number;
  ms: number;
  tokens: number;
};

export type EvalRun = {
  ranAt: string;
  provider: string;
  model_fast?: string;
  model_strong?: string;
  results: EvalResult[];
};

export const START = "<!-- EVAL:START -->";
export const END = "<!-- EVAL:END -->";

function median(xs: number[]): number {
  if (!xs.length) return 0;
  const s = [...xs].sort((a, b) => a - b);
  const mid = Math.floor(s.length / 2);
  return s.length % 2 ? s[mid] : Math.round((s[mid - 1] + s[mid]) / 2);
}

function mean(xs: number[]): number {
  return xs.length ? Math.round(xs.reduce((a, b) => a + b, 0) / xs.length) : 0;
}

export function summarize(runs: EvalRun[], sourceFiles: string[] = []): string {
  if (!runs.length) throw new Error("No eval runs to summarize.");

  const byCase = new Map<string, EvalResult[]>();
  for (const run of runs) {
    for (const r of run.results) {
      const list = byCase.get(r.case) ?? [];
      list.push(r);
      byCase.set(r.case, list);
    }
  }

  const all = runs.flatMap((r) => r.results);
  const correct = all.filter((r) => r.got === r.expected).length;
  const errors = all.filter((r) => r.got.startsWith("ERROR")).length;
  // Citation % only means something for cases that produced a draft.
  const drafted = all.filter((r) => r.verifiedPct > 0);

  const models = [...new Set(runs.map((r) => `${r.provider} / ${r.model_strong ?? "(default)"}`))].join(", ");
  const dates = runs.map((r) => r.ranAt).sort();

  const lines: string[] = [];
  lines.push(
    `Generated by \`scripts/update-readme-evals.ts\` from ${runs.length} run(s) of \`pnpm eval\` (${models}), ${dates[0].slice(0, 10)} to ${dates[dates.length - 1].slice(0, 10)}.`
  );
  lines.push("");
  lines.push(
    `**Verdict accuracy: ${correct}/${all.length} (${Math.round((100 * correct) / all.length)}%)** across ${byCase.size} case(s)` +
      (errors ? `, of which ${errors} case-run(s) ended in an error.` : ".")
  );
  if (drafted.length) {
    lines.push(`Mean citations verified, over the ${drafted.length} case-run(s) that produced a draft: ${mean(drafted.map((r) => r.verifiedPct))}%.`);
  }
  lines.push("");
  lines.push("| Case | Expected | Got (per run) | Correct | Citations verified | Median ms | Mean tokens |");
  lines.push("| --- | --- | --- | --- | --- | --- | --- |");
  for (const [name, rs] of [...byCase.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    const ok = rs.filter((r) => r.got === r.expected).length;
    const cites = rs.some((r) => r.verifiedPct > 0) ? `${mean(rs.map((r) => r.verifiedPct))}%` : "n/a";
    lines.push(
      `| ${name} | ${rs[0].expected} | ${rs.map((r) => r.got).join(", ")} | ${ok}/${rs.length} | ${cites} | ${median(rs.map((r) => r.ms))} | ${mean(rs.map((r) => r.tokens))} |`
    );
  }
  if (sourceFiles.length) {
    lines.push("");
    lines.push(`Source files: ${sourceFiles.map((f) => `\`${f}\``).join(", ")}.`);
  }
  return lines.join("\n");
}

export function replaceBlock(readme: string, body: string): string {
  const s = readme.indexOf(START);
  const e = readme.indexOf(END);
  if (s === -1 || e === -1 || e < s) throw new Error(`README is missing the ${START} / ${END} markers.`);
  return readme.slice(0, s + START.length) + "\n" + body + "\n" + readme.slice(e);
}

function main() {
  const root = path.resolve(__dirname, "..");
  const resultsDir = path.join(root, "evals", "results");
  const args = process.argv.slice(2).filter((a) => a !== "--");
  const files = args.length
    ? args.map((a) => path.resolve(a))
    : fs.existsSync(resultsDir)
      ? fs.readdirSync(resultsDir).filter((f) => f.endsWith(".json")).sort().map((f) => path.join(resultsDir, f))
      : [];

  if (!files.length) {
    console.error("No eval results found in evals/results/. Run `pnpm eval` first. README.md was not changed.");
    process.exit(1);
  }

  const runs = files.map((f) => JSON.parse(fs.readFileSync(f, "utf-8")) as EvalRun);
  const readmePath = path.join(root, "README.md");
  const body = summarize(runs, files.map((f) => path.relative(root, f)));
  fs.writeFileSync(readmePath, replaceBlock(fs.readFileSync(readmePath, "utf-8"), body));
  console.log(`Updated README.md eval block from ${files.length} file(s).`);
}

if (process.argv[1]?.endsWith("update-readme-evals.ts")) main();
